import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const browser=await chromium.launch({headless:true,...(process.env.E2E_CHROMIUM?{executablePath:process.env.E2E_CHROMIUM}:{})});
try {
  const page=await browser.newPage();
  const errors=[], network=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
  const file=pathToFileURL(resolve('standalone/index.html')).href;
  await page.goto(file+'#/meetings/projects');
  await page.getByLabel('프로젝트 이름',{exact:true}).fill('HTML 검증');
  await page.getByLabel('프로젝트 키',{exact:true}).fill('LOCAL');
  await page.getByRole('button',{name:'프로젝트 등록',exact:true}).click();
  await page.getByText('프로젝트를 등록했습니다.',{exact:false}).waitFor();
  await page.goto(file+'#/meetings/new');
  await page.locator('[name=title]').fill('HTML 회의 테스트');
  await page.getByLabel('등록한 프로젝트 선택').selectOption('LOCAL');
  await page.locator('#transcript').fill('참석자: 첫 번째 발언\n두 번째 발언');
  await page.getByRole('button',{name:'회의 저장',exact:true}).click();
  await page.waitForURL(/#\/meetings\/[^/]+$/);
  const meetingUrl=page.url();
  await page.getByRole('button',{name:'회의록 편집',exact:true}).click();
  const summary=page.locator('.minutes-grid textarea').nth(1);
  await summary.fill('직접 작성한 주요 안건');
  await page.getByRole('button',{name:'회의록 저장',exact:true}).click();
  await page.getByText('직접 작성한 주요 안건',{exact:true}).waitFor();
  await page.reload();
  await page.getByText('직접 작성한 주요 안건',{exact:true}).waitFor();
  await page.goto(meetingUrl+'?tab=transcript');
  await page.getByText('두 번째 발언',{exact:true}).first().waitFor();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'데이터 백업',exact:true}).click();
  assert.equal((await download).suggestedFilename(),'moa-backup.json');
  await page.setViewportSize({width:390,height:844});
  await page.goto(file+'#/dashboard');
  assert.equal(await page.locator('h1').count(),1);
  assert.deepEqual(errors,[]);
  assert.deepEqual(network,[]);
  console.log('PASS: file:// project, meeting, transcript, minutes save/reload, backup, mobile render; no network or browser errors');
} finally {await browser.close();}
